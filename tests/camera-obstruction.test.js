import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import RAPIER from '@dimforge/rapier3d-compat';
import {CameraObstruction} from '../src/camera/CameraObstruction.js';
await RAPIER.init();
const world=new RAPIER.World({x:0,y:-9.81,z:0});
const body=world.createRigidBody(RAPIER.RigidBodyDesc.dynamic());
world.createCollider(RAPIER.ColliderDesc.cuboid(.9,.7,2),body);
world.createCollider(RAPIER.ColliderDesc.cuboid(4,4,.2).setTranslation(0,0,-4));
world.step();
const root=new THREE.Object3D(),camera=new THREE.PerspectiveCamera();
camera.position.set(0,2,-7);camera.lookAt(0,.7,0);
const handler=new CameraObstruction(world),initialBody=body.translation();
assert.equal(handler.update(camera,root,body),true);
assert.ok(camera.position.z>-3.8&&camera.position.z<0,'Camera pulled in front of actual wall');
assert.deepEqual(body.translation(),initialBody,'Camera query does not move vehicle');
const blockedPosition=camera.position.toArray();
camera.position.set(7,2,0);camera.lookAt(0,.7,0);
assert.equal(handler.update(camera,root,body),false,'Own chassis excluded and clear side is not moved');
assert.deepEqual(camera.position.toArray(),[7,2,0]);
fs.writeFileSync('reports/camera-obstruction-results.json',JSON.stringify({at:new Date().toISOString(),passed:true,engine:'real Rapier world',blockedPosition,vehicleBodyUnchanged:true,ownBodyExcluded:true,limit:'Wall and clear-line ray test; not a complete screen-space or interior-geometry camera test.'},null,2));
world.free();console.log('PASS actual scene wall camera clearance and own body exclusion');
