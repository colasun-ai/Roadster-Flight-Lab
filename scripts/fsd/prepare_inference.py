#!/usr/bin/env python3
"""Extract the official inference graph, omitting training/metrics/plotting.

Forward, transition and every learned layer remain upstream source. The source
commit, original checkpoint and a full-output equivalence test are recorded.
"""
import subprocess
import ast
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
source = ROOT / 'external/Plan-R1'
target = ROOT / 'fsd-runtime/planr1'
target.mkdir(parents=True, exist_ok=True)
for folder in ['layers', 'modules', 'utils', 'transforms']:
    shutil.copytree(source / folder, target / folder, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
tree = ast.parse((source / 'model/PlanR1.py').read_text())
cls = next(node for node in tree.body if isinstance(node, ast.ClassDef))
cls.bases = [ast.Attribute(value=ast.Name(id='nn', ctx=ast.Load()), attr='Module', ctx=ast.Load())]
cls.body = [node for node in cls.body if isinstance(node, ast.FunctionDef) and
            node.name in ['__init__', 'plan_inference', 'transition']]
init = cls.body[0]
keep = []
for node in init.body:
    text = ast.unparse(node)
    if text.startswith('self.cls_loss ='):
        break
    if text == 'self.save_hyperparameters()':
        continue
    keep.append(node)
init.body = keep
imports = ast.parse('''import torch
import torch.nn as nn
from torch_geometric.data import Batch
from layers import TwoLayerMLP
from modules import Backbone, MapEncoder
from utils import sample_with_top_k_top_p, move_dict_to_device, transform_point_to_global_coordinate, wrap_angle
''').body
module = ast.Module(body=imports + [cls], type_ignores=[])
text = ast.unparse(ast.fix_missing_locations(module))
text = text.replace('torch.load(token_dict_path)', 'torch.load(token_dict_path, weights_only=True)')
(target / 'inference.py').write_text('# Derived from Apache-2.0 Plan-R1; generated by prepare_inference.py.\n' + text + '\n')
subprocess.run(['patch', str(target/'inference.py'), str(ROOT/'scripts/fsd/guided-inference.patch')], check=True)
shutil.copy2(source / 'LICENSE', target / 'LICENSE')
(target / 'tokens').mkdir(exist_ok=True)
shutil.copy2(source / 'tokens/tokens_1024.pt', target / 'tokens/tokens_1024.pt')
(ROOT / 'fsd-runtime/weights').mkdir(exist_ok=True)
shutil.copy2(source / 'ckpts/fine-tuning.ckpt', ROOT / 'fsd-runtime/weights/fine-tuning.ckpt')
manifest = {'upstream': 'https://github.com/XiaolongTang23/Plan-R1',
            'commit': '23bc54433599002f275c18b88cf261ab5e87d775',
            'changes': ['nn.Module base; removed training-only methods, rewards, metrics, plotting imports',
                        'safe token loading; optional navigation-based ranking of official top-96 ego tokens'],
            'files': {str(p.relative_to(target)): hashlib.sha256(p.read_bytes()).hexdigest()
                      for p in sorted(target.rglob('*')) if p.is_file()}}
(target / 'provenance.json').write_text(json.dumps(manifest, indent=2))
print('Prepared inference-only source. Equivalence testing is required before shipping.')
