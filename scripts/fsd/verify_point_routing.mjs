import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {RoadNetwork,at,project} from '../../src/fsd/RoadNetwork.js';
import {Autopilot} from '../../src/fsd/Autopilot.js';
import {roadPin,planToPoint,remainingDistance} from '../../src/fsd/PointNavigation.js';
const net=new RoadNetwork();
const lane=net.lanes.get('0:-120>0:0/0'),p=at(lane,52),near={...project(lane,p),lane};
const behind=roadPin(net,at(lane,18.4));
const loop=planToPoint(net,near,lane.id,behind,null);
assert.equal(loop[0],lane.id);assert.equal(loop.at(-1),lane.id);assert.ok(loop.length>4);
assert.ok(remainingDistance(net,near,loop,behind)>150);
const offroad=roadPin(net,{x:1060,z:660});
assert.ok(offroad.offset>15&&net.lanes.has(offroad.lane));
const ahead=roadPin(net,at(lane,74.5));
assert.ok(Math.abs(remainingDistance(net,near,[lane.id],ahead)-22.5)<.001);
const pilot=new Autopilot(net,null);pilot.destination='120:0>120:120/0';pilot.route=pilot.routeFrom(near);
const original=pilot.route.slice(),blocked=net.lanes.get(original.find((id,i)=>i>0&&!net.lanes.get(id).connector));
const actors=Array.from({length:32},(_,i)=>({lane:i<2?blocked:lane,s:8+(i%2)*8,speed:i<2?0:8}));
let green=0;while(net.light(blocked,green)!==0||net.light(blocked,green+6)!==0)green+=.5;
for(let i=0;i<13;i++){pilot.time=green+i*.5;pilot.observeQueues(near,actors);}
assert.ok(pilot.events.some(e=>e.event==='detour'));assert.equal(pilot.route.at(-1),original.at(-1));assert.ok(!pilot.route.includes(blocked.id));assert.deepEqual(pilot.route,pilot.routeFrom(near));
const record={sameLaneBehind:loop,offroad,pointDistanceMetres:22.5,traffic:32,blocked:blocked.id,original,alternative:pilot.route,events:pilot.events};
await fs.writeFile('reports/recovery/navigation.json',JSON.stringify(record,null,2));
console.log('PASS arbitrary road point, off-road snap, destination behind ego and queue-aware alternative');
const {escapePath,Recovery}=await import('../../src/fsd/Recovery.js');
const e={...at(lane,39),width:1.93,length:4.66,rearAxle:1.43};
const car={config:{maxInnerSteer:.64,wheelbase:2.875},forwardSpeed:()=>0};
const occupied=[{...at(lane,44.1),width:3,length:2.5},{...at(lane,36),width:4,length:2.5}];
const escapePilot={time:7,network:net,route:[lane.id],obstacles:[],events:[]};
assert.equal(escapePath(escapePilot,e,{actors:occupied},car),null);
const guard=new Recovery(),atLight={lane,s:lane.length-4};
while(net.light(lane,escapePilot.time)!==2)escapePilot.time+=.2;
assert.equal(guard.control(escapePilot,e,car,{actors:occupied},'红灯保护',atLight,0),null);
console.log('PASS occupied rear and normal red light do not authorize reversing');
